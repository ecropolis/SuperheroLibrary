#!/usr/bin/env node
/**
 * npm run check (after check-catalog.mjs, which builds dist/) — pins the cookie-consent element,
 * which is the one element this repo does not own.
 *
 * src/library/cookie-consent/CookieConsent.astro is a synced copy of ecropolis/ecropolis-consent's
 * src/CookieConsent.astro, written by `node bin/consent-sync.mjs update SuperheroLibrary` in that
 * repo. It is never edited here: a local edit is overwritten by the next sync and never reaches
 * the seven sites that run the widget.
 *
 * 1. The synced file still carries the canonical header (CANONICAL SOURCE, "Do NOT edit") and an
 *    @version, and it is the only CookieConsent.astro under src/.
 * 2. When ecropolis-consent is checked out beside this repo or any directory above it (or at
 *    $CONSENT_REPO, which then is the only place looked), the copy's @version equals that repo's
 *    package.json version and the canonical file's @version, and its bytes equal the canonical
 *    file's. A stale copy fails on the version; a copy edited in place fails on the bytes. A
 *    latest CHANGELOG heading that disagrees is reported. When the repo is not there (CI), this
 *    part is skipped with a note and the header check still holds.
 * 3. The demo takes the widget from the synced file (component and ?raw CSS); its script makes
 *    frames sandboxed to scripts only, never allow-same-origin; and the built page ships the
 *    widget only inside inert <template>s, one per mode, each with a stage for its frame. That
 *    isolation is what stops a demo click changing a visitor's real consent on
 *    superherotech.ai, which runs the widget itself.
 *
 * Exits 1 with one line per failed case.
 */
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SYNCED = 'src/library/cookie-consent/CookieConsent.astro';
const DEMO = 'src/components/demos/CookieConsentDemo.astro';
const failures = [];
const notes = [];
const fail = (msg) => failures.push(msg);
const finish = (stage) => {
  if (!failures.length) return;
  console.error(`check-cookie-consent failed (${stage}):`);
  for (const f of failures) console.error(`  - ${f}`);
  process.exit(1);
};
const versionOf = (src) => (src.match(/@version\s+([0-9]+\.[0-9]+\.[0-9]+)/) || [])[1];

// ------------------------------------------------------------- 1. the synced file
const syncedPath = join(root, SYNCED);
if (!existsSync(syncedPath)) {
  fail(`${SYNCED} is missing. Run \`node bin/consent-sync.mjs update SuperheroLibrary\` in ecropolis-consent.`);
  finish('synced file');
}
const synced = readFileSync(syncedPath, 'utf8');
const version = versionOf(synced);
if (!/CANONICAL SOURCE: ecropolis\/ecropolis-consent/.test(synced)) {
  fail(`${SYNCED} no longer names its canonical source (ecropolis/ecropolis-consent) in the header; it has been replaced or edited here.`);
}
if (!/Do NOT edit this file inside a site repo/.test(synced)) {
  fail(`${SYNCED} has lost its "Do NOT edit" header; it has been edited here.`);
}
if (!version) fail(`${SYNCED} has no @version line.`);

const others = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name === 'CookieConsent.astro' && p !== syncedPath) others.push(relative(root, p));
  }
})(join(root, 'src'));
for (const o of others) fail(`${o} is a second copy of the widget; the only one belongs at ${SYNCED}, written by consent-sync.`);
finish('synced file');

// ------------------------------------------------------------ 2. against canonical
function findConsentRepo() {
  const candidates = [];
  if (process.env.CONSENT_REPO) candidates.push(process.env.CONSENT_REPO);
  // Beside this repo, or beside any directory above it (worktrees live deeper down).
  else for (let d = root; ; d = dirname(d)) {
    candidates.push(join(d, 'ecropolis-consent'));
    if (dirname(d) === d) break;
  }
  for (const c of candidates) {
    const pkg = join(c, 'package.json');
    if (!existsSync(pkg)) continue;
    try {
      if (JSON.parse(readFileSync(pkg, 'utf8')).name === '@ecropolis/consent') return c;
    } catch {}
  }
  return null;
}

const consent = findConsentRepo();
if (!consent) {
  notes.push('ecropolis-consent is not checked out beside this repo (or at $CONSENT_REPO), so the version and byte comparison was skipped; the header check above still ran.');
} else {
  const pkgVersion = JSON.parse(readFileSync(join(consent, 'package.json'), 'utf8')).version;
  const changelog = existsSync(join(consent, 'CHANGELOG.md')) ? readFileSync(join(consent, 'CHANGELOG.md'), 'utf8') : '';
  const logVersion = (changelog.match(/^##\s+([0-9]+\.[0-9]+\.[0-9]+)/m) || [])[1];
  const canonical = readFileSync(join(consent, 'src/CookieConsent.astro'), 'utf8');
  const canonVersion = versionOf(canonical);
  const where = relative(root, consent) || consent;

  if (logVersion && logVersion !== pkgVersion) {
    notes.push(`${where}: package.json says ${pkgVersion} but the latest CHANGELOG heading is ${logVersion}; compared against the component's own @version ${canonVersion}.`);
  }
  if (version !== canonVersion || version !== pkgVersion) {
    fail(`${SYNCED} is v${version}; ecropolis-consent (${where}) is v${canonVersion} (package.json ${pkgVersion}). Stale: run \`node bin/consent-sync.mjs update SuperheroLibrary\` there.`);
  } else if (synced !== canonical) {
    fail(`${SYNCED} is v${version}, the same as ecropolis-consent, but its bytes differ. Either it was edited here (port the change upstream, bump the version, sync) or ecropolis-consent has unreleased changes; \`node bin/consent-sync.mjs diff SuperheroLibrary\` there says which.`);
  }
  const sites = existsSync(join(consent, 'sites.json')) ? JSON.parse(readFileSync(join(consent, 'sites.json'), 'utf8')) : { sites: [] };
  const entry = sites.sites.find((s) => s.name === 'SuperheroLibrary');
  if (!entry) notes.push(`${where}/sites.json does not list SuperheroLibrary, so consent-sync cannot report or refresh this copy.`);
  else if (entry.component !== SYNCED) fail(`${where}/sites.json syncs SuperheroLibrary to ${entry.component}, not ${SYNCED}.`);
  finish('against ecropolis-consent');
  notes.unshift(`matches ecropolis-consent v${canonVersion} byte for byte (${where}).`);
}

// ---------------------------------------------------------------- 3. the demo
const demo = readFileSync(join(root, DEMO), 'utf8');
if (!/import CookieConsent from '\.\.\/\.\.\/library\/cookie-consent\/CookieConsent\.astro';/.test(demo)) {
  fail(`${DEMO} must import the widget from the synced file.`);
}
if (!/from '\.\.\/\.\.\/library\/cookie-consent\/CookieConsent\.astro\?raw';/.test(demo)) {
  fail(`${DEMO} must take the widget's CSS from the synced file (?raw), not a copy.`);
}
const sandboxes = [...demo.matchAll(/setAttribute\('sandbox',\s*'([^']*)'\)/g)].map((m) => m[1]);
if (sandboxes.length !== 1 || sandboxes[0] !== 'allow-scripts') {
  fail(`${DEMO} must make its frames with setAttribute('sandbox', 'allow-scripts') and nothing more; found ${JSON.stringify(sandboxes)}.`);
}
if (/allow-same-origin['"]/.test(demo)) fail(`${DEMO} grants allow-same-origin somewhere; the widget inside could reach the host page’s cookies and storage.`);
if (!/\.title = /.test(demo)) fail(`${DEMO} no longer titles its frames for screen readers.`);
finish('demo source');

const pagePath = join(root, 'dist/cookie-consent/index.html');
if (!existsSync(pagePath)) {
  fail('dist/cookie-consent/index.html is missing; check-catalog.mjs builds it first.');
  finish('built page');
}
const html = readFileSync(pagePath, 'utf8');
const templates = [...html.matchAll(/<template\b([^>]*\bdata-ccd-widget\b[^>]*)>([\s\S]*?)<\/template>/g)];
const modes = templates.map((t) => (t[1].match(/data-ccd-mode="([^"]+)"/) || [])[1]);
for (const m of ['opt-out', 'opt-in']) if (!modes.includes(m)) fail(`The demo page has no ${m} widget.`);
for (const [, attrs, body] of templates) {
  const m = (attrs.match(/data-ccd-mode="([^"]+)"/) || [])[1];
  if (!/id="cc-banner"/.test(body)) fail(`The ${m} template does not contain the widget's bar.`);
  if (!/data-cc="accept"/.test(body) || !/data-cc="decline"/.test(body)) fail(`The ${m} template lacks Accept or Decline.`);
}
const outside = html.replace(/<template\b[\s\S]*?<\/template>/g, '');
if (/id="cc-banner"/.test(outside)) fail('The widget is rendered into the page itself, outside a <template>; it would act on the host page.');
const stages = [...outside.matchAll(/<div\b[^>]*\bdata-ccd-stage\b[^>]*>/g)].map((m) => m[0]);
if (stages.length !== templates.length) fail(`The demo page has ${templates.length} widget templates but ${stages.length} frame stages.`);
for (const st of stages) if (!/data-ccd-title="[^"]+"/.test(st)) fail('A frame stage has no title for its frame.');
if (/<iframe\b[^>]*data-ccd-frame/.test(html)) fail('The demo page ships a frame in its HTML; the script makes them (the gallery index allows no iframe at load).');
if (!/data-ccd-css="[^"]*\.cc-banner/.test(html)) fail('The demo page does not carry the widget CSS taken from the synced file.');
finish('built page');

for (const n of notes) console.log(`check-cookie-consent: ${n}`);
console.log(`check-cookie-consent ok: synced v${version}, header intact, demo isolated in ${stages.length} sandboxed frames.`);
